package com.company.employee.service;

import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Collectors;

import org.springframework.stereotype.Service;

import com.company.employee.exception.EmployeeNotFoundException;
import com.company.employee.model.Employee;
import com.company.employee.repository.EmployeeRepository;

// Service layer: business logic between controller and repository
@Service
public class EmployeeService {

    private final EmployeeRepository repo;

    public EmployeeService(EmployeeRepository repo) {
        this.repo = repo;
    }

    public Employee add(Employee e) {
        return repo.save(e);                 // id is generated by MySQL
    }

    public List<Employee> getAll() {
        return repo.findAll();
    }

    public Employee getById(int id) {
        return repo.findById(id).orElseThrow(() -> new EmployeeNotFoundException(id));
    }

    public Employee update(int id, Employee e) {
        getById(id);                         // 404 if it doesn't exist
        e.setId(id);
        repo.update(e);
        return e;
    }

    public void delete(int id) {
        getById(id);                         // 404 if it doesn't exist
        repo.deleteById(id);
    }

    // ----- Extra (collections, useful for viva) -----

    // List filter: employees of one department (case-insensitive)
    public List<Employee> getByDepartment(String department) {
        return repo.findAll().stream()
                .filter(e -> e.getDepartment().equalsIgnoreCase(department))
                .collect(Collectors.toList());
    }

    // Map: department -> average salary (TreeMap keeps departments sorted A-Z)
    public Map<String, Double> averageSalaryByDepartment() {
        return repo.findAll().stream()
                .collect(Collectors.groupingBy(Employee::getDepartment, TreeMap::new,
                         Collectors.averagingDouble(Employee::getSalary)));
    }
}
